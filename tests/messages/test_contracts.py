"""Contract tests: one valid example of every type, and a few invalid ones.

Every agent's own tests should round-trip these through parse_message, and each
stub answers with the valid examples first (docs/PLAN.md, "Contract tests").
"""

import json
from pathlib import Path

import pytest

from plan_my_stay.enums import MessageType
from plan_my_stay.messages import MessageParseError, examples, parse_message, serialize
from plan_my_stay.messages.payloads import PAYLOAD_MODELS

EXAMPLES_DIR = Path(examples.__file__).parent / "contract_examples"


def test_there_is_a_valid_example_for_every_message_type():
    assert {m.type for m in map(parse_message, map(json.dumps, examples.valid_examples().values()))} == set(MessageType)


@pytest.mark.parametrize("name", sorted(examples.valid_examples()))
def test_valid_example_round_trips_unchanged(name):
    raw = examples.valid_examples()[name]
    msg = parse_message(json.dumps(raw))

    assert isinstance(msg.payload, PAYLOAD_MODELS[msg.type])
    assert json.loads(serialize(msg)) == raw


@pytest.mark.parametrize("name", sorted(examples.invalid_examples()))
def test_invalid_example_is_rejected_with_the_expected_code(name):
    raw, expected_code = examples.invalid_examples()[name]
    text = raw if isinstance(raw, str) else json.dumps(raw)

    with pytest.raises(MessageParseError) as err:
        parse_message(text)
    assert err.value.code is expected_code


def test_the_plan_s_own_request_and_proposal_examples_are_valid():
    plan_request = examples.valid_examples()["request"]
    plan_proposal = examples.valid_examples()["proposal"]

    assert plan_request["payload"]["slots"][0]["window"] == {"start": "17:30", "end": "21:00"}
    assert plan_proposal["payload"]["items"][0]["item_id"] == "rest-urban-vegan-kitchen"


def test_json_files_on_disk_match_the_python_examples():
    """The files teammates read are generated by scripts/export_contracts.py; they must not drift."""
    for name, raw in examples.valid_examples().items():
        assert json.loads((EXAMPLES_DIR / "valid" / f"{name}.json").read_text()) == raw
    for name, (raw, code) in examples.invalid_examples().items():
        on_disk = json.loads((EXAMPLES_DIR / "invalid" / f"{name}.json").read_text())
        assert on_disk == {"expected_code": code.value, "message": raw}
